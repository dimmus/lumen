LUMEN_TEST(spec_parses_every_form) {
    LUMEN_CHECK(parse_background("")->kind == background_kind::lumen);
    LUMEN_CHECK(parse_background("lumen")->kind == background_kind::lumen);
    auto c = parse_background("#112233");
    LUMEN_CHECK(c && c->kind == background_kind::color && c->color == 0xFF112233u);
    auto c2 = parse_background("color:#aaBBcc");
    LUMEN_CHECK(c2 && c2->color == 0xFFAABBCCu);
    auto g = parse_background("gradient:#000000:#ffffff");
    LUMEN_CHECK(g && g->kind == background_kind::gradient && g->color2 == 0xFFFFFFFFu &&
                g->angle_deg == 90.f);
    auto g2 = parse_background("gradient:#000000:#ffffff:45");
    LUMEN_CHECK(g2 && g2->angle_deg == 45.f);
    auto i = parse_background("image:/a/b.png:fit");
    LUMEN_CHECK(i && i->kind == background_kind::image && i->path == "/a/b.png" &&
                i->fit == background_fit::fit);
    auto i2 = parse_background("image:/a/b:c.png"); // a ':' in the path is not a mode
    LUMEN_CHECK(i2 && i2->path == "/a/b:c.png" && i2->fit == background_fit::fill);
    auto i3 = parse_background("/x/y.jpg");
    LUMEN_CHECK(i3 && i3->kind == background_kind::image && i3->path == "/x/y.jpg");
    LUMEN_CHECK(!parse_background("#12345"));
    LUMEN_CHECK(!parse_background("gradient:#000000"));
    LUMEN_CHECK(!parse_background("gradient:#000000:#ffffff:x"));
    LUMEN_CHECK(!parse_background("sparkles"));
    LUMEN_CHECK(!parse_background("image:"));
}

LUMEN_TEST(color_fills_opaque) {
    std::vector<std::uint32_t> px(6 * 4 + 2, 0u);
    lx::shell::render_color(px.data(), 6, 4, 6, 0x00123456u);
    for (int i = 0; i < 24; ++i)
        LUMEN_CHECK(px[static_cast<std::size_t>(i)] == 0xFF123456u);
    LUMEN_CHECK(px[24] == 0u); // nothing past the rows
}

LUMEN_TEST(gradient_reaches_its_stops_and_dithers_within_one_lsb) {
    const int w = 512, h = 8;
    std::vector<std::uint32_t> px(static_cast<std::size_t>(w) * h);
    lx::shell::render_gradient(px.data(), w, h, w, 0xFF000000u, 0xFFFFFFFFu, 0.f);
    // The first and last pixel centres sit 1/1024 inside the stops; linear light lifts the
    // dark end most (t = 0.001 encodes to sRGB 3).
    LUMEN_CHECK(near(px[0], 0xFF000000u, 4));
    LUMEN_CHECK(near(px[w - 1], 0xFFFFFFFFu, 2));
    // Linear light: the middle is brighter than sRGB's halfway grey (0x80) — ~0xBC.
    const int mid = ch(px[w / 2], 16);
    LUMEN_CHECK(mid > 0xB0 && mid < 0xC8);
    // One colour: every pixel within ±1 of it (the dither is ±½ LSB before rounding).
    lx::shell::render_gradient(px.data(), w, h, w, 0xFF406080u, 0xFF406080u, 30.f);
    bool all = true;
    for (auto p : px)
        all = all && near(p, 0xFF406080u, 1);
    LUMEN_CHECK(all);
    // A slow ramp — 16 levels over 512 px — undithered is stair steps of 32 px and more
    // (linear light widens some levels): bands. Dithered, each edge between two levels is
    // a mix of both; only the middle of a level, which ±½ LSB cannot move, stays flat.
    lx::shell::render_gradient(px.data(), w, h, w, 0xFF202020u, 0xFF303030u, 0.f);
    int run = 1, longest = 1;
    for (int x = 1; x < w; ++x) {
        run = px[static_cast<std::size_t>(x)] == px[static_cast<std::size_t>(x - 1)] ? run + 1 : 1;
        longest = std::max(longest, run);
    }
    std::printf("slow ramp: longest run %d px\n", longest);
    LUMEN_CHECK(longest < 24);
}

LUMEN_TEST(lumen_default_is_dark_smooth_and_fast) {
    const int w = 1920, h = 1080;
    std::vector<std::uint32_t> px(static_cast<std::size_t>(w) * h);
    const auto t0 = std::chrono::steady_clock::now();
    lx::shell::render_lumen(px.data(), w, h, w);
    const double ms = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
    std::printf("render_lumen 1920x1080: %.1f ms\n", ms);
    LUMEN_CHECK(ms < 500.0); // a few ms on one core; generous for slow CI hosts
    long long sum = 0;
    int worst = 0;
    for (int y = 0; y < h; ++y)
        for (int x = 0; x < w; ++x) {
            const std::uint32_t p = px[static_cast<std::size_t>(y) * w + x];
            LUMEN_CHECK((p >> 24) == 0xFFu);
            sum += ch(p, 16) + ch(p, 8) + ch(p, 0);
            if (x > 0) {
                const std::uint32_t q = px[static_cast<std::size_t>(y) * w + x - 1];
                worst = std::max({worst, std::abs(ch(p, 16) - ch(q, 16)), std::abs(ch(p, 8) - ch(q, 8)),
                                  std::abs(ch(p, 0) - ch(q, 0))});
            }
        }
    const double mean = static_cast<double>(sum) / (3.0 * w * h);
    LUMEN_CHECK(mean > 10.0 && mean < 90.0); // dark, not black
    LUMEN_CHECK(worst <= 2);                 // no edges, no bands: dither steps only
    // Resolution independent: the same place on a quarter-size render has the same colour.
    std::vector<std::uint32_t> small(static_cast<std::size_t>(w / 4) * (h / 4));
    lx::shell::render_lumen(small.data(), w / 4, h / 4, w / 4);
    LUMEN_CHECK(near(small[static_cast<std::size_t>(h / 8) * (w / 4) + w / 8],
                     px[static_cast<std::size_t>(h / 2) * w + w / 2], 3));
}

LUMEN_TEST(image_placement_modes) {
    // A 2x2 image: red, green / blue, transparent.
    const std::uint32_t img[4] = {0xFFFF0000u, 0xFF00FF00u, 0xFF0000FFu, 0x00000000u};
    std::vector<std::uint32_t> px(6 * 4);
    // Centred 1:1 over the colour.
    lx::shell::render_image(px.data(), 6, 4, 6, img, 2, 2, background_fit::center, 0xFF101010u);
    LUMEN_CHECK(px[0] == 0xFF101010u);
    LUMEN_CHECK(px[1 * 6 + 2] == 0xFFFF0000u && px[1 * 6 + 3] == 0xFF00FF00u);
    LUMEN_CHECK(px[2 * 6 + 2] == 0xFF0000FFu && px[2 * 6 + 3] == 0xFF101010u); // transparent shows under
    // Tiled from the top-left.
    lx::shell::render_image(px.data(), 6, 4, 6, img, 2, 2, background_fit::tile, 0xFF101010u);
    LUMEN_CHECK(px[0] == 0xFFFF0000u && px[2] == 0xFFFF0000u && px[4] == 0xFFFF0000u);
    LUMEN_CHECK(px[3 * 6 + 5] == 0xFF101010u && px[3 * 6 + 4] == 0xFF0000FFu);
    LUMEN_CHECK(px[2 * 6 + 4] == 0xFFFF0000u);
}

LUMEN_TEST(decodes_png_jpeg_webp) {
    const auto formats = lx::shell::background_formats();
    std::vector<std::uint32_t> out;
    int w = 0, h = 0;
    if (formats.png) {
        const std::string f = write_temp(k_png, sizeof(k_png), ".png");
        LUMEN_CHECK(lx::shell::decode_background(f, 4, 2, background_fit::stretch, out, w, h));
        LUMEN_CHECK(w == 4 && h == 2);
        LUMEN_CHECK(out[0] == 0xFFFF0000u && out[1] == 0xFF00FF00u && out[2] == 0xFF0000FFu);
        LUMEN_CHECK((out[3] >> 24) == 128 && ch(out[3], 16) == 128); // premultiplied
        std::remove(f.c_str());
    }
    if (formats.jpeg) {
        // 256x128 shown filled on a 64x32 output: decoded at 1/4 by the DCT, no resample.
        const std::string f = write_temp(k_jpeg, sizeof(k_jpeg), ".jpg");
        LUMEN_CHECK(lx::shell::decode_background(f, 64, 32, background_fit::fill, out, w, h));
        LUMEN_CHECK(w == 64 && h == 32);
        LUMEN_CHECK(near(out[static_cast<std::size_t>(16) * 64 + 32], 0xFF3070C0u, 3));
        // Fitted inside a 100x100 output: 100x50 (scaled down from 128 wide... the decode at
        // 1/2 is 128x64, then area-averaged).
        LUMEN_CHECK(lx::shell::decode_background(f, 100, 100, background_fit::fit, out, w, h));
        LUMEN_CHECK(w == 100 && h == 50);
        std::remove(f.c_str());
    }
    if (formats.webp) {
        const std::string f = write_temp(k_webp, sizeof(k_webp), ".webp");
        LUMEN_CHECK(lx::shell::decode_background(f, 16, 8, background_fit::fill, out, w, h));
        LUMEN_CHECK(w == 16 && h == 8);
        LUMEN_CHECK(near(out[0], 0xFFC03070u, 2));
        std::remove(f.c_str());
    }
    if (formats.svg) {
        const char svg[] = "<svg xmlns='http://www.w3.org/2000/svg' width='10' height='5'>"
                           "<rect width='10' height='5' fill='#20a040'/></svg>";
        const std::string f = write_temp(reinterpret_cast<const unsigned char*>(svg), sizeof(svg) - 1, ".svg");
        // Rendered at the size it is shown: 40x20 for a fill of 40x10.
        LUMEN_CHECK(lx::shell::decode_background(f, 40, 10, background_fit::fill, out, w, h));
        LUMEN_CHECK(w == 40 && h == 20);
        LUMEN_CHECK(near(out[static_cast<std::size_t>(10) * 40 + 20], 0xFF20A040u, 1));
        std::remove(f.c_str());
    }
    std::printf("decoders: png=%d jpeg=%d webp=%d svg=%d\n", formats.png, formats.jpeg, formats.webp,
                formats.svg);
}

LUMEN_TEST(unreadable_image_falls_back_to_the_default) {
    lx::shell::background_spec s{};
    s.kind = background_kind::image;
    s.path = "/nonexistent/wallpaper.png";
    std::vector<std::uint32_t> a(64 * 32), b(64 * 32);
    LUMEN_CHECK(!lx::shell::render_background(s, a.data(), 64, 32, 64));
    lx::shell::render_lumen(b.data(), 64, 32, 64);
    LUMEN_CHECK(a == b);
}

