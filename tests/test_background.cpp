int ch(std::uint32_t p, unsigned shift) { return static_cast<int>((p >> shift) & 0xFFu); }
bool near(std::uint32_t p, std::uint32_t q, int tol) {
    return std::abs(ch(p, 16) - ch(q, 16)) <= tol && std::abs(ch(p, 8) - ch(q, 8)) <= tol &&
           std::abs(ch(p, 0) - ch(q, 0)) <= tol;
}

std::string write_temp(const unsigned char* data, std::size_t n, const char* ext) {
    char path[] = "/tmp/lumen-bg-XXXXXX";
    const int fd = mkstemp(path);
    if (fd < 0)
        return {};
    (void)!::write(fd, data, n);
    ::close(fd);
    std::string named = std::string(path) + ext;
    std::rename(path, named.c_str());
    return named;
}

