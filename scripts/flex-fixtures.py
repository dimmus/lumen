#!/usr/bin/env python3
"""Transcribe Taffy's Chrome-generated flexbox fixtures into tests/layout_flex_fixtures.inc.

Taffy (github.com/DioxusLabs/taffy, MIT) generates its layout fixtures by laying HTML out in
Chrome; tests/xml/flex/<name>__border_box_ltr.xml holds each one's input styles and Chrome's
rounded results. This keeps the fixtures whose every property lx.layout:flex supports and
writes them as a C++ table: per node, its parent's index, its style as CSS declarations, and
Chrome's x, y, width, height relative to its parent. Fixtures left out are listed with the
reason on stderr.

Usage:
    git clone --depth 1 https://github.com/DioxusLabs/taffy /tmp/taffy
    python3 -I scripts/flex-fixtures.py /tmp/taffy/tests/xml/flex tests/layout_flex_fixtures.inc <taffy-sha>
"""
import os
import sys
import xml.etree.ElementTree as ET

LEN_PROPS = {
    'width', 'height', 'min-width', 'min-height', 'max-width', 'max-height', 'flex-basis',
    'margin-top', 'margin-right', 'margin-bottom', 'margin-left',
    'padding-top', 'padding-right', 'padding-bottom', 'padding-left',
    'border-top', 'border-right', 'border-bottom', 'border-left',
    'top', 'right', 'bottom', 'left', 'row-gap', 'column-gap',
}
ENUMS = {
    'flex-direction': {'row', 'column', 'row-reverse', 'column-reverse'},
    'flex-wrap': {'wrap', 'wrap-reverse', 'nowrap'},
    'align-items': {'flex-start', 'flex-end', 'start', 'end', 'center', 'stretch'},
    'align-self': {'flex-start', 'flex-end', 'start', 'end', 'center', 'stretch', 'auto'},
    'align-content': {'flex-start', 'flex-end', 'start', 'end', 'center', 'stretch',
                      'space-between', 'space-around', 'space-evenly'},
    'justify-content': {'flex-start', 'flex-end', 'start', 'end', 'center',
                        'space-between', 'space-around', 'space-evenly'},
    'position': {'relative', 'absolute'},
    'overflow-x': {'visible', 'hidden', 'scroll'},
    'overflow-y': {'visible', 'hidden', 'scroll'},
    'display': {'flex'},
    'direction': {'ltr'},
}
NUMS = {'flex-grow', 'flex-shrink'}

# Supported properties, unsupported semantics.
EXCLUDED = {
    # The containers are `position: static` in the HTML: the absolute children's containing
    # block is the root. lx.layout:flex makes every container a containing block.
    'absolute_layout_static_container_static_position_content_box':
        'position: static containers',
    # A percentage row gap of an auto-height container: Chrome treats the height as
    # indefinite for percentages even after layout; lx.layout:flex treats a size its caller
    # fixed as definite (Taffy's `known_dimensions_are_definite` is not modelled).
    'gap_row_gap_percentage_wrapping': 'percentage of a known but indefinite size',
}


def length_ok(v):
    if v == 'auto':
        return True
    for suf in ('px', '%'):
        if v.endswith(suf):
            v = v[:-len(suf)]
            break
    try:
        float(v)
        return True
    except ValueError:
        return False


def check(div):
    if (div.text or '').strip():
        return 'text content (needs a text measure)'
    for k, v in div.attrib.items():
        if k in LEN_PROPS:
            if not length_ok(v):
                return f'{k}={v}'
        elif k in ENUMS:
            if v not in ENUMS[k]:
                return f'{k}={v}'
        elif k in NUMS:
            float(v)
        elif k == 'scrollbar-width':
            if 'scroll' in (div.attrib.get('overflow-x'), div.attrib.get('overflow-y')) and v != '0':
                return 'scrollbar gutter'
        else:
            return f'unsupported {k}'
    for kid in div:
        r = check(kid)
        if r:
            return r
    return None


def style_of(div, is_root):
    parts = []
    for k, v in div.attrib.items():
        if k in ('direction', 'scrollbar-width', 'display'):
            continue
        if k == 'position' and (is_root or v == 'relative'):
            continue
        if k in LEN_PROPS and v != 'auto' and not v.endswith(('px', '%')):
            v = v + 'px'
        parts.append(f'{k}:{v}')
    return ';'.join(parts)


def walk(div, node, parent, rows, is_root):
    idx = len(rows)
    rows.append((parent, style_of(div, is_root), node.attrib['x'], node.attrib['y'],
                 node.attrib['width'], node.attrib['height']))
    kids_in, kids_ex = list(div), list(node)
    assert len(kids_in) == len(kids_ex)
    for d, n in zip(kids_in, kids_ex):
        walk(d, n, idx, rows, False)


def main():
    xml_dir, out_path, sha = sys.argv[1], sys.argv[2], sys.argv[3]
    suffix = '__border_box_ltr.xml'
    names = sorted(f[:-len(suffix)] for f in os.listdir(xml_dir) if f.endswith(suffix))
    out = [
        '// Generated by scripts/flex-fixtures.py from Taffy\'s Chrome-generated fixtures',
        f'// (github.com/DioxusLabs/taffy {sha}, tests/xml/flex, MIT). Per node:',
        '// {parent, CSS declarations, Chrome\'s x, y, width, height relative to the parent}.',
        '// Do not edit; regenerate.',
    ]
    kept = 0
    for name in names:
        if name in EXCLUDED:
            print(f'skip {name}: {EXCLUDED[name]}', file=sys.stderr)
            continue
        t = ET.parse(os.path.join(xml_dir, name + suffix)).getroot()
        if t.attrib.get('use-rounding') != 'true':
            print(f'skip {name}: unrounded expectations', file=sys.stderr)
            continue
        vp = t.find('viewport')
        if vp.attrib.get('width') != 'max-content' or vp.attrib.get('height') != 'max-content':
            print(f'skip {name}: viewport', file=sys.stderr)
            continue
        root = t.find('input')[0]
        reason = check(root)
        if reason:
            print(f'skip {name}: {reason}', file=sys.stderr)
            continue
        rows = []
        walk(root, t.find('expectations')[0], -1, rows, True)
        out.append(f'{{"{name}", {{')
        for (p, s, x, y, w, h) in rows:
            out.append(f'    {{{p}, "{s}", {x}, {y}, {w}, {h}}},')
        out.append('}},')
        kept += 1
    with open(out_path, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'kept {kept}', file=sys.stderr)


if __name__ == '__main__':
    main()
